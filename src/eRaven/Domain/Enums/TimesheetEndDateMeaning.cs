namespace eRaven.Domain.Enums;

/// <summary>
/// Як трактувати дату, яку вводить користувач як "по/закінчення".
/// </summary>
public enum TimesheetEndDateMeaning
{
    /// <summary>
    /// Введена дата є останнім днем ЦЬОГО коду (inclusive).
    /// Приклад: 100 "по 10.01" => 100.To = 10.01, 30 з 11.01.
    /// </summary>
    LastDayOfThisCode = 0,

    /// <summary>
    /// Введена дата є першим днем НАСТУПНОГО базового коду (effective/return date).
    /// Приклад: ВП "закінчення 10.01" => 30 з 10.01, ВП.To = 09.01.
    /// </summary>
    FirstDayOfNextCode = 1
}