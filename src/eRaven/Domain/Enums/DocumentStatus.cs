/// <summary>
/// Операційний стан документа/факту.
/// Draft/Posted прибрано: система працює як "операційна", без чернеток.
/// </summary>
public enum DocumentStatus
{
    /// <summary>Активний (чинний) факт/документ.</summary>
    Active = 0,

    /// <summary>
    /// Скасований/визнаний недійсним (Void/Cancel) через компенсацію.
